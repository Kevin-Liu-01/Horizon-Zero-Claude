/**
 * Credits generator (pipeline lane; plan §10.2). One source, two surfaces:
 *
 *   node tools/licences/credits.mjs --md     README "Credits" section body
 *   node tools/licences/credits.mjs --json   rows for src/ui/menu.js CREDITS
 *
 * Every CC-BY and MIT `attribution` string is emitted VERBATIM (A-licence-
 * manifest checks both surfaces for it); CC0 sources are thanked; OFL fonts
 * are listed with their licence. Rows marked `ip: true` are never credited
 * (they are deleted at their R30 wave, not licensed). Output is sorted and
 * deterministic, so brand can diff it (A-credits, W4).
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadManifest } from './lib.mjs';

const GROUPS = [
  { key: 'cc-by', head: 'Attribution required (CC BY)', test: (r) => /^CC-BY-/.test(r.licence) },
  { key: 'code', head: 'Code (MIT)', test: (r) => r.licence === 'MIT' },
  { key: 'ofl', head: 'Typefaces (SIL Open Font License 1.1)', test: (r) => r.licence === 'OFL-1.1' },
  { key: 'cc0', head: 'Thanks (CC0, no attribution required)', test: (r) => r.licence === 'CC0-1.0' },
];

export function creditRows(manifest = loadManifest()) {
  const rows = (manifest?.rows || []).filter((r) => !r.ip);
  const out = [];
  for (const g of GROUPS) {
    const lines = [];
    const seen = new Set();
    for (const r of rows.filter(g.test)) {
      const text = r.attribution || `${r.title} — ${r.author}${r.source_url && /^https?:/.test(r.source_url) ? ` (${r.source_url})` : ''}`;
      if (seen.has(text)) continue;
      seen.add(text);
      lines.push({ id: r.id, text });
    }
    lines.sort((a, b) => a.text.localeCompare(b.text, 'en'));
    if (lines.length) out.push({ group: g.key, head: g.head, lines });
  }
  return out;
}

export function creditsMarkdown(manifest = loadManifest()) {
  const parts = ['<!-- generated by tools/licences/credits.mjs from public/LICENSES.json; do not edit by hand -->', ''];
  for (const g of creditRows(manifest)) {
    parts.push(`**${g.head}**`, '');
    for (const l of g.lines) parts.push(`- ${l.text}`);
    parts.push('');
  }
  parts.push('Full manifest: `public/LICENSES.json`; licence texts: `public/licences/`.');
  return `${parts.join('\n')}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--json')) console.log(JSON.stringify(creditRows(), null, 2));
  else process.stdout.write(creditsMarkdown());
}
