const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, '../../..');
export const KTX_VERSION = 'v4.4.2';

/** Encoder settings, one place. */
export const SETTINGS = Object.freeze({
  uastc: ['--encode', 'uastc', '--uastc-quality', '2', '--zstd', '18'],
  etc1s: ['--encode', 'basis-lz', '--clevel', '4', '--qlevel', '255'],
  raw: ['--zstd', '9'],
  mips: ['--generate-mipmap', '--mipmap-filter', 'box'],
  /** below this edge an image is an exact-data table (palette, lookup row): stored uncompressed */
  exactEdge: 16,
});

/** GPU bytes per pixel after transcoding, as Chrome on the reference Mac picks (ASTC 4x4 / ETC2). */
export const GPU_BPP = Object.freeze({ uastc: 1, etc1s: 0.5, etc1sAlpha: 1, raw: 4, rgba8: 4 });

/* ------------------------------------------------------------------ the tool */
export function ktxBin(explicit = null) {
  const bin = explicit || process.env.CALIMA_KTX || path.join(os.homedir(), '.calima-r5/downloads/ktx-software/tool/bin/ktx');
  if (!existsSync(bin)) {
    const e = new Error(`ktx tool not found at ${bin} (KTX-Software ${KTX_VERSION}; pass --ktx or set CALIMA_KTX)`);
    /** @type {any} */ (e).code = 'KTX_MISSING';
    throw e;
  }
  const v = execFileSync(bin, ['--version'], { encoding: 'utf8' }).trim();
  if (!v.includes(KTX_VERSION)) throw new Error(`ktx tool at ${bin} is "${v}", expected ${KTX_VERSION}`);
  return bin;
}

/**
 * Encode PNG file(s) (one per array layer) to KTX2 bytes.
 * @param {{ bin: string, pngs: string[], out: string, mode: 'uastc'|'etc1s'|'raw', srgb: boolean, alpha: boolean, mips: boolean, wrap?: boolean }} o
 */
function ktxCreate({ bin, pngs, out, mode, srgb, alpha, mips, wrap = false }) {
  const ch = mode === 'raw' || alpha ? 'R8G8B8A8' : 'R8G8B8';
  const args = ['create', '--format', `${ch}_${srgb ? 'SRGB' : 'UNORM'}`, '--assign-tf', srgb ? 'srgb' : 'linear',
    '--assign-primaries', 'bt709', '--testrun'];
  if (pngs.length > 1) args.push('--layers', String(pngs.length));
  if (mips) args.push(...SETTINGS.mips, '--mipmap-wrap', wrap ? 'wrap' : 'clamp');
  args.push(...SETTINGS[mode], ...pngs, out);
  execFileSync(bin, args, { stdio: ['ignore', 'pipe', 'pipe'] });
  return readFileSync(out);
}

/** Decode any image to PNG on disk; report whether its alpha is used. */
async function toPng(bytes, file) {
  const { data, info } = await sharp(bytes, { unlimited: true }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let alpha = false;
  for (let i = 3; i < data.length; i += 4) if (data[i] !== 255) { alpha = true; break; }
  await sharp(data, { raw: { width: info.width, height: info.height, channels: 4 } }).png({ compressionLevel: 1 }).toFile(file);
  return { width: info.width, height: info.height, alpha };
}

const mipBytes = (w, h, bpp, mips) => {
  let s = 0;
  for (let l = 0; ; l++) {
    const lw = Math.max(1, w >> l), lh = Math.max(1, h >> l);
    s += lw * lh * bpp;
    if (!mips || (lw === 1 && lh === 1)) break;
  }
  return s;
};
const gpuBpp = (mode, alpha) => (mode === 'etc1s' ? (alpha ? GPU_BPP.etc1sAlpha : GPU_BPP.etc1s) : GPU_BPP[mode]);

/* ------------------------------------------------------------------ GLB bytes */
const GLB_MAGIC = 0x46546c67, CHUNK_JSON = 0x4e4f534a, CHUNK_BIN = 0x004e4942;

/** @param {Buffer} buf */
export function readGlb(buf) {
  if (buf.readUInt32LE(0) !== GLB_MAGIC) throw new Error('not a GLB');
  const jl = buf.readUInt32LE(12);
  if (buf.readUInt32LE(16) !== CHUNK_JSON) throw new Error('GLB: first chunk is not JSON');
  const json = JSON.parse(buf.subarray(20, 20 + jl).toString('utf8'));
  let bin = Buffer.alloc(0);
  const o = 20 + jl;
  if (o + 8 <= buf.length && buf.readUInt32LE(o + 4) === CHUNK_BIN) bin = buf.subarray(o + 8, o + 8 + buf.readUInt32LE(o));
  return { json, bin };
}

/** @param {any} json @param {Buffer} bin */
export function writeGlb(json, bin) {
  let js = Buffer.from(JSON.stringify(json), 'utf8');
  const jp = (4 - (js.length % 4)) % 4;
  js = Buffer.concat([js, Buffer.alloc(jp, 0x20)]);
  const bp = (4 - (bin.length % 4)) % 4;
  const b = Buffer.concat([bin, Buffer.alloc(bp)]);
  const head = Buffer.alloc(12);
  head.writeUInt32LE(GLB_MAGIC, 0); head.writeUInt32LE(2, 4);
  head.writeUInt32LE(12 + 8 + js.length + (b.length ? 8 + b.length : 0), 8);
  const jh = Buffer.alloc(8); jh.writeUInt32LE(js.length, 0); jh.writeUInt32LE(CHUNK_JSON, 4);
  const parts = [head, jh, js];
  if (b.length) { const bh = Buffer.alloc(8); bh.writeUInt32LE(b.length, 0); bh.writeUInt32LE(CHUNK_BIN, 4); parts.push(bh, b); }
  return Buffer.concat(parts);
}

/**
 * Rebuild buffer 0 (the GLB's BIN) with some bufferViews' bytes replaced. Every region of buffer 0 that anything
 * points at (plain bufferViews and EXT_meshopt_compression payloads) is copied in its original order, 16-byte
 * aligned; offsets are rewritten. Nothing else in the JSON moves.
 * @param {any} json @param {Buffer} bin @param {Map<number, Buffer>} replace bufferView index -> new bytes
 */
export function relayoutBin(json, bin, replace) {
  /** @type {{ off: number, len: number, refs: { obj: any, key: string, lenKey: string }[], bytes: Buffer | null }[]} */
  const regions = [];
  const byKey = new Map();
  const add = (obj, key, lenKey, off, len, bytes = null) => {
    const k = `${off}:${len}`;
    let r = byKey.get(k);
    if (!r) { r = { off, len, refs: [], bytes: null }; byKey.set(k, r); regions.push(r); }
    r.refs.push({ obj, key, lenKey });
    if (bytes) r.bytes = bytes;
  };
  (json.bufferViews || []).forEach((bv, i) => {
    if (bv.buffer === 0) add(bv, 'byteOffset', 'byteLength', bv.byteOffset || 0, bv.byteLength, replace.get(i) || null);
    const m = bv.extensions?.EXT_meshopt_compression;
    if (m && m.buffer === 0) add(m, 'byteOffset', 'byteLength', m.byteOffset || 0, m.byteLength);
  });
  regions.sort((a, b) => a.off - b.off);
  const parts = [];
  let at = 0;
  for (const r of regions) {
    const pad = (16 - (at % 16)) % 16;
    if (pad) { parts.push(Buffer.alloc(pad)); at += pad; }
    const bytes = r.bytes || bin.subarray(r.off, r.off + r.len);
    for (const ref of r.refs) { ref.obj[ref.key] = at; ref.obj[ref.lenKey] = bytes.length; }
    parts.push(bytes); at += bytes.length;
  }
  const out = Buffer.concat(parts);
  if (json.buffers?.[0]) json.buffers[0].byteLength = out.length;
  return out;
}

const COLOR_SLOTS = new Set(['baseColorTexture', 'emissiveTexture', 'diffuseTexture', 'specularGlossinessTexture',
  'sheenColorTexture', 'specularColorTexture']);
const MIP_FILTERS = new Set([9984, 9985, 9986, 9987]);

/** For each image: is it colour, and does any of its samplers minify through mips? @param {any} json */
export function imageUses(json) {
  /** @type {Map<number, { srgb: boolean, linear: boolean, mips: boolean, slots: Set<string> }>} */
  const use = new Map();
  const texSlots = new Map();
  const walk = (o, slot) => {
    if (!o || typeof o !== 'object') return;
    if (typeof o.index === 'number' && slot && /Texture$/.test(slot)) {
      if (!texSlots.has(o.index)) texSlots.set(o.index, new Set());
      texSlots.get(o.index).add(slot);
    }
    for (const [k, v] of Object.entries(o)) if (v && typeof v === 'object') walk(v, k);
  };
  for (const m of json.materials || []) walk(m, null);
  (json.textures || []).forEach((t, ti) => {
    const src = t.extensions?.KHR_texture_basisu?.source ?? t.source;
    if (src == null) return;
    const s = t.sampler != null ? json.samplers?.[t.sampler] : null;
    const u = use.get(src) || { srgb: false, linear: false, mips: false, slots: new Set() };
    const slots = texSlots.get(ti) || new Set(['(unbound)']);
    for (const sl of slots) { u.slots.add(sl); if (COLOR_SLOTS.has(sl)) u.srgb = true; else u.linear = true; }
    if (!s || s.minFilter == null || MIP_FILTERS.has(s.minFilter)) u.mips = true;
    use.set(src, u);
  });
  return use;
}

/**
 * Convert one GLB's images to KTX2.
 * @param {Buffer} buf @param {{ bin: string, tmp: string, raw?: boolean, label?: string }} o
 */
export async function convertGlb(buf, { bin, tmp, raw = false, label = '' }) {
  const { json, bin: data } = readGlb(buf);
  const use = imageUses(json);
  const replace = new Map();
  const rows = [];
  for (const [ii, img] of (json.images || []).entries()) {
    if (img.mimeType === 'image/ktx2') { rows.push({ file: label, image: img.name || `#${ii}`, mode: 'ktx2 (kept)' }); continue; }
    if (img.bufferView == null) throw new Error(`${label}: image ${ii} is external (${img.uri}); only embedded images are handled`);
    const bv = json.bufferViews[img.bufferView];
    const before = data.subarray(bv.byteOffset || 0, (bv.byteOffset || 0) + bv.byteLength);
    const u = use.get(ii) || { srgb: false, linear: true, mips: true, slots: new Set(['(unused)']) };
    if (u.srgb && u.linear) throw new Error(`${label}: image ${img.name || ii} is used as colour AND as data (${[...u.slots]}); split it in its recipe`);
    const png = path.join(tmp, `img-${ii}.png`);
    const { width, height, alpha } = await toPng(before, png);
    const exact = Math.max(width, height) < SETTINGS.exactEdge;
    const mode = raw || exact ? 'raw' : 'uastc';
    const out = ktxCreate({ bin, pngs: [png], out: path.join(tmp, `img-${ii}.ktx2`), mode, srgb: u.srgb, alpha, mips: u.mips });
    replace.set(img.bufferView, out);
    img.mimeType = 'image/ktx2';
    rows.push({ file: label, image: img.name || `#${ii}`, slots: [...u.slots].join('|'), mode: exact && !raw ? 'raw (exact table)' : mode,
      srgb: u.srgb, alpha, mips: u.mips, width, height, bytesBefore: before.length, bytesAfter: out.length,
      gpuBefore: mipBytes(width, height, 4, u.mips), gpuAfter: mipBytes(width, height, gpuBpp(mode, alpha), u.mips) });
  }
  if (!replace.size) return { glb: buf, rows, changed: false };
  for (const t of json.textures || []) {
    if (t.source == null) continue;
    const img = json.images[t.source];
    if (img?.mimeType !== 'image/ktx2') continue;
    t.extensions = { ...(t.extensions || {}), KHR_texture_basisu: { source: t.source } };
    delete t.source;
  }
  const add = (k) => { json[k] = [...new Set([...(json[k] || []), 'KHR_texture_basisu'])]; };
  add('extensionsUsed'); add('extensionsRequired');
  const newBin = relayoutBin(json, data, replace);
  return { glb: writeGlb(json, newBin), rows, changed: true };
}

/* ------------------------------------------------------------------ ground arrays */
/** The WebP sources of one ground array: `<root>/public/textures/ground/<id>_<part>.webp` per layer. */
const groundSource = (root, id, part) => path.join(root, 'public/textures/ground', `${id}_${part}.webp`);
export const GROUND_SOURCES = Object.freeze(Object.values(LAYER_FILES).flat().flatMap((id) =>
  ['a', 'n'].map((p) => `public/textures/ground/${id}_${p}.webp`)));

/** Make sure the ground WebP sources exist under some root; run the ground recipe into scratch if not. */
async function groundSourceRoot(root, tmp) {
  if (GROUND_SOURCES.every((f) => existsSync(path.join(root, f)))) return root;
  const scratch = path.join(tmp, 'ground-src');
  mkdirSync(scratch, { recursive: true });
  const mod = await import(pathToFileURL(path.join(ROOT, 'tools/build/ground/gen-ground-layers.mjs')).href);
  await mod.build({ out: scratch });
  return scratch;
}

/**
 * Encode the ground texture arrays into `<outRoot>/public/textures/ground/{big,small}_{a,n}.ktx2`.
 * @param {{ bin: string, srcRoot: string, outRoot: string, tmp: string, raw?: boolean }} o
 */
export async function encodeGround({ bin, srcRoot, outRoot, tmp, raw = false }) {
  const src = await groundSourceRoot(srcRoot, tmp);
  const rows = [];
  for (const [group, ids] of Object.entries(LAYER_FILES)) {
    for (const part of ['a', 'n']) {
      const pngs = [];
      let alpha = false;
      let before = 0;
      for (const id of ids) {
        const f = groundSource(src, id, part);
        const bytes = readFileSync(f);
        before += bytes.length;
        const png = path.join(tmp, `ground-${id}-${part}.png`);
        const m = await toPng(bytes, png);
        const N = /** @type {any} */ (LAYER_SIZE)[group];
        if (m.width !== N || m.height !== N) throw new Error(`${f}: ${m.width}×${m.height}, the array wants ${N}²`);
        alpha ||= m.alpha;
        pngs.push(png);
      }
      // colour: ETC1S, tagged sRGB so the encoder weighs error perceptually (the shader decodes it; the page
      // samples it as data, see src/core/ktx2.js `colorSpace: 'none'`). Normal XY + roughness + AO: UASTC.
      const mode = raw ? 'raw' : part === 'a' ? 'etc1s' : 'uastc';
      const rel = layerArrayPath(group, part);
      const out = path.join(outRoot, rel);
      mkdirSync(path.dirname(out), { recursive: true });
      const bytes = ktxCreate({ bin, pngs, out: path.join(tmp, `ground-${group}-${part}.ktx2`), mode, srgb: part === 'a', alpha, mips: true, wrap: true });
      writeFileSync(out, bytes);
      const N = /** @type {any} */ (LAYER_SIZE)[group];
      rows.push({ file: rel, image: `${ids.join('+')} (${part === 'a' ? 'albedo + height' : 'normal XY, roughness, AO'})`, mode, srgb: part === 'a', alpha,
        mips: true, width: N, height: N, layers: ids.length, bytesBefore: before, bytesAfter: bytes.length,
        gpuBefore: mipBytes(N, N, 4, true) * ids.length, gpuAfter: mipBytes(N, N, gpuBpp(mode, alpha), true) * ids.length });
    }
  }
  return rows;
}

/* ------------------------------------------------------------------ the step */
const git = (root, ...a) => execFileSync('git', ['-C', root, ...a], { encoding: 'utf8' }).trim();
const listGlbs = (root) => {
  try { return git(root, 'ls-files', '--cached', '--others', '--exclude-standard', '--', 'public/models').split('\n').filter((f) => f.endsWith('.glb')); }
  catch { return []; }
};

/**
 * Encode a tree. `srcRoot` is read, `outRoot` written (the same root for the in-place build).
 * @param {{ srcRoot?: string, outRoot?: string, raw?: boolean, only?: string | null, ktx?: string | null, glbs?: string[] | null, ground?: boolean }} o
 */
export async function encodeTree({ srcRoot = ROOT, outRoot = srcRoot, raw = false, only = null, ktx = null, glbs = null, ground = true } = {}) {
  const bin = ktxBin(ktx);
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'calima-ktx2-'));
  const rows = [];
  const written = [];
  try {
    for (const rel of (glbs || listGlbs(srcRoot)).filter((f) => !only || f.includes(only))) {
      const buf = readFileSync(path.join(srcRoot, rel));
      const r = await convertGlb(buf, { bin, tmp, raw, label: rel });
      rows.push(...r.rows);
      if (r.changed || outRoot !== srcRoot) {
        const out = path.join(outRoot, rel);
        mkdirSync(path.dirname(out), { recursive: true });
        writeFileSync(out, r.glb);
        written.push(rel);
      }
    }
    if (ground && (!only || 'public/textures/ground'.includes(only) || only.includes('ground'))) {
      const g = await encodeGround({ bin, srcRoot, outRoot, tmp, raw });
      rows.push(...g);
      written.push(...g.map((x) => x.file));
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return { rows, written, totals: totals(rows) };
}

/** @param {any[]} rows */
export function totals(rows) {
  const t = { textures: 0, bytesBefore: 0, bytesAfter: 0, gpuBefore: 0, gpuAfter: 0, byMode: /** @type {Record<string, number>} */ ({}) };
  for (const r of rows) {
    if (r.bytesAfter == null) continue;
    t.textures += r.layers || 1; t.bytesBefore += r.bytesBefore; t.bytesAfter += r.bytesAfter;
    t.gpuBefore += r.gpuBefore; t.gpuAfter += r.gpuAfter;
    t.byMode[r.mode] = (t.byMode[r.mode] || 0) + (r.layers || 1);
  }
  return t;
}

/**
 * The build driver's hook (tools/build/build-assets.mjs): after a recipe has written its outputs under `out`,
 * its GLBs are converted in place and, if it wrote the ground WebP sources, the ground arrays are encoded and the
 * consumed WebP intermediates (exactly the recipe's own listed outputs) are removed from `out`.
 * @param {{ outputs: string[], out: string, ktx?: string | null }} o
 */
export async function ktx2Outputs({ outputs, out, ktx = null }) {
  const glbs = outputs.filter((f) => f.startsWith('public/') && f.endsWith('.glb'));
  const groundWebp = outputs.filter((f) => GROUND_SOURCES.includes(f));
  if (!glbs.length && !groundWebp.length) return { files: [], rows: [] };
  if (groundWebp.length && groundWebp.length !== GROUND_SOURCES.length) throw new Error(`ktx2: a recipe wrote ${groundWebp.length} of the ${GROUND_SOURCES.length} ground sources`);
  const r = await encodeTree({ srcRoot: out, outRoot: out, glbs, ground: groundWebp.length > 0, ktx });
  for (const f of groundWebp) unlinkSync(path.join(out, f));   // the recipe's own intermediates, by name
  return { files: r.written, rows: r.rows };
}

/** Textures under public/ that are not KTX2 (loose image files, and images inside GLBs). */
export function unencoded(root = ROOT) {
  const out = [];
  let files = [];
  try { files = git(root, 'ls-files', '--cached', '--others', '--exclude-standard', '--', 'public').split('\n').filter(Boolean); } catch { /* */ }
  for (const f of files) {
    if (!existsSync(path.join(root, f))) continue;
    if (/\.(png|jpe?g|webp|gif|avif)$/i.test(f) && !f.startsWith('public/fonts/')) out.push(f);
    else if (f.endsWith('.glb')) {
      const { json } = readGlb(readFileSync(path.join(root, f)));
      for (const [i, im] of (json.images || []).entries()) if (im.mimeType !== 'image/ktx2') out.push(`${f}#${im.name || i} (${im.mimeType})`);
    }
  }
  return out;
}

