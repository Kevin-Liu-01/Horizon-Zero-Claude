// @ts-check
/**
 * KTX2 texture step (M0.10). Every texture that ships under public/ is a KTX2 file: block-compressed
 * Basis Universal (UASTC or ETC1S) that the page transcodes to the GPU's own format (ASTC, BC7, ETC2,
 * BC1/3), or, for tiny exact-data tables, uncompressed RGBA8 inside the KTX2 container.
 *
 *   node tools/build/pipeline/ktx2.mjs                      encode every shipped texture under public/ in place
 *   node tools/build/pipeline/ktx2.mjs --raw <dir>          write the UNCOMPRESSED reference set (the same textures,
 *                                                           same mips, RGBA8 KTX2) into <dir>, a repo-shaped root
 *                                                           outside the repository (the M0.10 A/B renders against it)
 *   node tools/build/pipeline/ktx2.mjs --check              list textures under public/ that are not KTX2 (exit 1 if any)
 *   options: --root <repo-shaped root to read> · --only <path substring> · --ktx <path of the ktx tool> · --quiet
 *
 * WHAT IS ENCODED HOW (TECH §7 "textures"):
 *   ground colour layers (public/textures/ground/*_a)   ETC1S (BasisLZ) at the top quality level, perceptual
 *   ground normal layers (*_n: normal XY, roughness, AO) UASTC
 *   every texture inside a GLB (base colour, normal,      UASTC: these are the people, Brea, the kit and the
 *     ORM, emissive)                                        Instruments, all of which a face or close camera sees
 *   any texture with an edge under 16 px                  RGBA8 + Zstandard: palettes and lookup rows whose texels
 *                                                           are exact material values and are sampled NEAREST
 * Colour images are tagged sRGB, data images linear. Mips are generated by the encoder with a box filter (the same
 * filter the GPU's generateMipmap uses), so a texture that mipmapped at runtime before is mipmapped the same way now;
 * an image whose samplers never minify through mips (NEAREST / LINEAR) ships one level.
 *
 * The ground ships as two texture arrays per size, the layout `src/world/island/layers.js` defines
 * (`LAYER_FILES`, `layerArrayUrl`): `public/textures/ground/{big,small}_{a,n}.ktx2`. Their sources are the
 * WebP pairs `tools/build/ground/gen-ground-layers.mjs` writes; when those are not on disk the recipe is run into
 * a scratch root first (it is deterministic and reads no third-party file).
 *
 * GLBs are edited as bytes, not through a scene graph: only the image bytes and the JSON that names them change
 * (images become `image/ktx2`, textures point at them through KHR_texture_basisu, which is listed as required), and
 * every other buffer region (meshopt payloads, accessors, animation) is copied verbatim, so geometry is
 * bit-identical. Already-KTX2 images are left alone: the step is idempotent.
 *
 * The encoder is the Khronos KTX-Software `ktx` tool (v4.4.2), a tool download outside the repository:
 * `--ktx`, else $CALIMA_KTX, else ~/.calima-r5/downloads/ktx-software/tool/bin/ktx. Output is deterministic
 * (same input, same bytes). The step replaces the texture half of the Round-4 tools/optimize.mjs (retired with it).
 */
