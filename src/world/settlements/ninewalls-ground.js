import { ISLAND_SCALE as S } from '../island/extent.js';
import { WALLS, CENTRE, DWELLINGS, PLACES, ROAD, dwellingPlace, inSpan, TERRACE } from './ninewalls-layout.js';

/**
 * NINEWALLS' GROUND: the terraces, the pads and the walk in (M2 wave 2, area B; the orchestrator's ruling 4 after the
 * wave 1 blockout: "Ninewalls stands on terraces, each crescent wall a riser"). Plain data and pure maths, no three,
 * so the island recipe, every terrain worker and node run the same code. The recipe calls `buildNinewallsGround` once
 * after its own grids (and the Holds' blockout) exist, and applies `ninewallsHeight` last in `heightAt`; outside the
 * village's footprint the ground is the island's to the bit (`ninewallsHeight` returns the same float).
 *
 *   TERRACES  the ground between two crescent walls is levelled ACROSS (radially) at the mean of the ground it was cut
 *             from at that bearing, smoothed along the arc (TERRACE.smoothM): the cross-fall of the hillside goes, the
 *             climb along the crescent stays (a terrace is level across, as the Holds' pit terraces are). Each wall is
 *             the riser between two terraces: the ground stands at the HIGH side's level under the wall and on a ledge
 *             in front of its low face (TERRACE.ledge), then falls to the low terrace down a battered bank (its width
 *             TERRACE.bankK of the riser's height, within bankMin..bankMax); the wall's drystone skin covers the bank. A
 *             terrace is levelled only where both of its walls stand: towards a wall's end (TERRACE.fadeM of arc) the
 *             levelling hands back to the hillside, so a wall ends on its own ground and nothing is cut where no wall
 *             holds it. Inside the innermost wall (the dwellings' core) and outside the outer one the hillside stays.
 *   PADS      every dwelling stands on a level pad cut and filled at its centre's ground (its back sunk into the slope,
 *             bible §4: "drystone houses sunk in lapilli"); the tree, the cistern, the Brazier, the counter and the tube
 *             mouth's forecourt likewise.
 *   THE ROAD  the walk in (ROAD in ninewalls-layout.js, generated by tools/build/settlements/ninewalls-road.mjs): a
 *             bench TERRACE.roadHalf m each side of its centreline at the road's own height, handed back to the
 *             hillside over TERRACE.roadMargin m.
 *
 * Frame: the recipe's authored (e, n); engine x = e S, z = -n S. Bearings as in the layout (0 north, 90 east).
 */

const D2R = Math.PI / 180;
const ss = (e0, e1, x) => { const t = Math.min(1, Math.max(0, (x - e0) / (e1 - e0))); return t * t * (3 - 2 * t); };
const NB = 360;   // the tables' bearing resolution (1 deg)
const NW = WALLS.length, NR = NW - 1;

const G = {
  ready: false, natural: null,
  /** per ring j (between WALLS[j + 1] and WALLS[j]): its level at each bearing */
  L: Array.from({ length: NR }, () => new Float64Array(NB)),
  /** per wall k: the natural ground just inside and just outside its faces */
  nIn: Array.from({ length: NW }, () => new Float64Array(NB)),
  nOut: Array.from({ length: NW }, () => new Float64Array(NB)),
  /** per wall k: its weight at each bearing (1 inside its span, easing to 0 at its ends) */
  w: Array.from({ length: NW }, () => new Float64Array(NB)),
  pads: [], road: null, reach: 0,
};

/** The natural ground (the island before this file) at an engine point; valid once built. */
export function ninewallsNatural(x, z) { return G.natural ? G.natural(x / S, -z / S) : 0; }

const polarXZ = (b, r) => ({ x: CENTRE.x + Math.sin(b * D2R) * r, z: CENTRE.z - Math.cos(b * D2R) * r });
const lerpB = (arr, b) => { const f = ((b % 360) + 360) % 360, i = Math.floor(f) % NB, t = f - Math.floor(f); return arr[i] + (arr[(i + 1) % NB] - arr[i]) * t; };

/** A wall's weight at bearing b: 1 inside its span, easing to 0 over TERRACE.fadeM of arc at each end, 0 outside. */
function wallWeight(w, b) {
  if (!inSpan(w, b)) return 0;
  const fade = (TERRACE.fadeM / w.r) / D2R;
  let a = b - w.from; a -= Math.floor(a / 360) * 360;
  const span = w.to - w.from;
  return ss(0, fade, a) * ss(0, fade, span - a);
}

/** The pads (engine frame): { x, z, c, s (rotation), hw, hd (half sizes, m; a disc when hd is null), level, blend }. */
function buildPads(N) {
  const out = [];
  for (const d of DWELLINGS) {
    const p = dwellingPlace(d);
    out.push({ id: d.id, x: p.x, z: p.z, c: Math.cos(p.ry), s: Math.sin(p.ry), hw: d.w / 2 + TERRACE.padEdge, hd: d.d / 2 + TERRACE.padEdge, level: N(p.x, p.z), blend: TERRACE.padBlend });
  }
  const disc = (id, q, r, blend = TERRACE.padBlend) => out.push({ id, x: q.x, z: q.z, hw: r, hd: null, level: N(q.x, q.z), blend });
  disc('tree', PLACES.tree, PLACES.tree.canopyR * 0.9);
  disc('cistern', PLACES.cistern, PLACES.cistern.r + 1.4);
  disc('brazier', PLACES.brazier, 1.4);
  const rect = (id, q, b, hw, hd, off = 0) => {
    const ry = Math.atan2(CENTRE.x - q.x, CENTRE.z - q.z), dx = Math.sin(ry) * off, dz = Math.cos(ry) * off;
    out.push({ id, x: q.x + dx, z: q.z + dz, c: Math.cos(ry), s: Math.sin(ry), hw, hd, level: N(q.x + dx, q.z + dz), blend: TERRACE.padBlend });
  };
  rect('counter', PLACES.counter, PLACES.counter.b, PLACES.counter.w / 2 + 1.2, PLACES.counter.d / 2 + 1.4);
  // the tube mouth's forecourt: in front of its face, toward the tree
  const M = PLACES.tubeMouth;
  rect('tubeMouth', M, M.b, M.w / 2 + 1.8, 2.6, 2.4);
  return out;
}

/**
 * Read the reference heights once (`natural(e, n)`, authored frame: the recipe's height before this file). Idempotent;
 * about 24 k samples.
 */
export function buildNinewallsGround(natural) {
  if (G.ready) return G;
  G.natural = natural;
  const N = (x, z) => natural(x / S, -z / S);
  for (let k = 0; k < NW; k++) {
    const w = WALLS[k];
    for (let i = 0; i < NB; i++) {
      const pi = polarXZ(i, w.r - w.t / 2 - 0.05), po = polarXZ(i, w.r + w.t / 2 + 0.05);
      G.nIn[k][i] = N(pi.x, pi.z); G.nOut[k][i] = N(po.x, po.z); G.w[k][i] = wallWeight(w, i);
    }
  }
  for (let j = 0; j < NR; j++) {
    const outer = WALLS[j], inner = WALLS[j + 1];
    const r0 = inner.r + inner.t / 2, r1 = outer.r - outer.t / 2, rm = (r0 + r1) / 2;
    const raw = new Float64Array(NB);
    for (let i = 0; i < NB; i++) {
      let s = 0;
      for (let q = 0; q <= 4; q++) { const p = polarXZ(i, r0 + (r1 - r0) * (0.1 + 0.8 * q / 4)); s += N(p.x, p.z); }
      raw[i] = s / 5;
    }
    // smoothed along the arc: a Gaussian of TERRACE.smoothM metres at the ring's middle
    const sig = Math.max(0.5, (TERRACE.smoothM / rm) / D2R), R = Math.ceil(sig * 3);
    for (let i = 0; i < NB; i++) {
      let a = 0, ws = 0;
      for (let d = -R; d <= R; d++) { const g = Math.exp(-(d * d) / (2 * sig * sig)); a += raw[(i + d + NB * 4) % NB] * g; ws += g; }
      G.L[j][i] = a / ws;
    }
  }
  G.pads = buildPads(N);
  // the road: cumulative lengths and its bounding box
  if (ROAD.length > 1) {
    const L = [0];
    let x0 = Infinity, x1 = -Infinity, z0 = Infinity, z1 = -Infinity;
    for (let i = 0; i < ROAD.length; i++) {
      const p = ROAD[i];
      if (i) L.push(L[i - 1] + Math.hypot(p[0] - ROAD[i - 1][0], p[1] - ROAD[i - 1][1]));
      x0 = Math.min(x0, p[0]); x1 = Math.max(x1, p[0]); z0 = Math.min(z0, p[1]); z1 = Math.max(z1, p[1]);
    }
    const m = TERRACE.roadHalf + TERRACE.roadMargin + 0.5;
    G.road = { L, x0: x0 - m, x1: x1 + m, z0: z0 - m, z1: z1 + m };
  }
  G.reach = WALLS[0].r + WALLS[0].t / 2 + TERRACE.ledge + TERRACE.bankMax + 1;
  G.ready = true;
  return G;
}

/** Ring j's level at bearing b over natural ground h: its levelled height where both its walls stand, else h. */
function ringLevel(j, b, h) {
  const W = Math.min(lerpB(G.w[j], b), lerpB(G.w[j + 1], b));
  return W > 0 ? h + (lerpB(G.L[j], b) - h) * W : h;
}

/** The ground on wall k's two faces at bearing b (the rings' levels there): { inner, outer }. */
export function wallFaces(k, b) {
  const nI = lerpB(G.nIn[k], b), nO = lerpB(G.nOut[k], b);
  return { inner: k < NR ? ringLevel(k, b, nI) : nI, outer: k > 0 ? ringLevel(k - 1, b, nO) : nO };
}

/** A riser's bank width (m) for a step of `rise` m. */
export const bankOf = (rise) => Math.min(TERRACE.bankMax, Math.max(TERRACE.bankMin, rise * TERRACE.bankK));

/**
 * The village's ground at an authored point, over the island's height `h` there. Returns `h` itself outside the
 * village and the road.
 */
export function ninewallsHeight(e, n, h) {
  if (!G.ready) return h;
  const x = e * S, z = -n * S, dx = x - CENTRE.x, dz = z - CENTRE.z, r = Math.hypot(dx, dz);
  const R = G.road, inRoad = R && x > R.x0 && x < R.x1 && z > R.z0 && z < R.z1;
  if (r > G.reach && !inRoad) return h;
  let out = h;
  if (r <= G.reach) {
    const b = ((Math.atan2(dx, -dz) / D2R) + 360) % 360;
    // the ring this point is in: j = -1 outside the outer wall, 0..NR-1 a terrace, NR the core
    let j = NR;
    for (let k = 0; k < NW; k++) if (r >= WALLS[k].r) { j = k - 1; break; }
    out = j >= 0 && j < NR ? ringLevel(j, b, h) : h;
    // the risers either side: wall j (outside this point) and wall j + 1 (inside it)
    for (const k of [j, j + 1]) {
      if (k < 0 || k >= NW) continue;
      const wk = lerpB(G.w[k], b);
      if (wk <= 0) continue;
      const w = WALLS[k], f = wallFaces(k, b), hi = Math.max(f.inner, f.outer), lo = Math.min(f.inner, f.outer);
      const lowIn = f.inner < f.outer;
      const s = (r - w.r) * (lowIn ? -1 : 1);   // + on the low side
      const half = w.t / 2, bw = bankOf(hi - lo);
      if (s < -half || s > half + TERRACE.ledge + bw) continue;
      let v;
      if (s <= half + TERRACE.ledge) v = hi;
      else v = out + (hi - out) * (1 - (s - half - TERRACE.ledge) / bw);
      out += (v - out) * wk;
    }
    // the pads (only inside the innermost wall: the dwellings, the places)
    if (r < WALLS[NW - 1].r - WALLS[NW - 1].t / 2) {
      for (const p of G.pads) {
        const ox = x - p.x, oz = z - p.z;
        let d;
        if (p.hd == null) d = Math.hypot(ox, oz) - p.hw;
        else {
          const lx = ox * p.c - oz * p.s, lz = ox * p.s + oz * p.c;
          const ex = Math.abs(lx) - p.hw, ez = Math.abs(lz) - p.hd;
          d = Math.hypot(Math.max(ex, 0), Math.max(ez, 0)) + Math.min(Math.max(ex, ez), 0);
        }
        if (d < p.blend) out += (p.level - out) * (1 - ss(0, p.blend, Math.max(0, d)));
      }
    }
  }
  if (inRoad) {
    // the nearest point of the centreline: its height there, and how far off it this point is
    let best = Infinity, hr = 0;
    for (let i = 0; i + 1 < ROAD.length; i++) {
      const a = ROAD[i], c = ROAD[i + 1], ux = c[0] - a[0], uz = c[1] - a[1], l2 = ux * ux + uz * uz;
      const t = Math.min(1, Math.max(0, ((x - a[0]) * ux + (z - a[1]) * uz) / l2));
      const d = Math.hypot(x - a[0] - ux * t, z - a[1] - uz * t);
      if (d < best) { best = d; hr = a[2] + (c[2] - a[2]) * t; }
    }
    const M = TERRACE.roadHalf + TERRACE.roadMargin;
    if (best < M) out += (hr - out) * (1 - ss(TERRACE.roadHalf, M, best));
  }
  return out;
}

/** For the rows: the tables as built (levels, weights, pads). */
export function ninewallsGroundTables() { return G; }
